"""Write the Studio assembly script for a batch of accessories (tools/accessories/assemble_<batch>.luau).

python acc_assemble.py <batch-name> <Item>[,<Item>...] [--root E:/NH-Work/acc] [--ids ids.json]

The Luau script (NH Combat Test, Edit; run after the owner's File > Import 3D of art/group-upload-accessories/<batch>/
NHAcc_<Item>.fbx and the Bulk Import of its maps) turns each imported model into ReplicatedStorage.NHAccessories.<Item>:
every piece MeshPart gets NHMount, NHFit (its bounding-box centre on the nominal R6 part, from the builder), NHFitBody,
NHSway / NHSwayKeepOut / NHSwayLock, NHSeat and NHHairFit (head pieces), and a SurfaceAppearance (colour, normal,
roughness, metalness, emissive mask; alpha pieces: their RGBA colour map, AlphaMode Transparency). ids.json maps an
uploaded image name (NHAcc_<Item>_<kind>) to its group asset id (read by name from the group's creations list).
"""
import json, os, sys

args = sys.argv[1:]
batch = args[0]
items = args[1].split(",")
ROOT = args[args.index("--root") + 1] if "--root" in args else "E:/NH-Work/acc"
IDS = json.load(open(args[args.index("--ids") + 1])) if "--ids" in args else {}
OUT = os.path.join("E:/Nightmare-Highschool/tools/accessories", f"assemble_{batch}.luau")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
SEAT = 1.93 - 1.5   # the headband, above the head centre, on the nominal head


def lua_v3(v):
    return f"Vector3.new({v[0]:.4f}, {v[1]:.4f}, {v[2]:.4f})"


def hair_fit_string(fits):
    if not fits:
        return None
    parts, ks, zs = [], [], []
    for h, f in sorted(fits.items()):
        if f is None:
            parts.append(f"{h}=x")
        else:
            parts.append(f"{h}={f[0]:.3f},{f[1]:.3f}")
            ks.append(f[0]); zs.append(f[1])
    # any other hair (the built styles, outside catalog hairs): the generous end of the measured fits (unverified)
    ks.sort(); zs.sort()
    if ks:
        q = int(len(ks) * 0.9) - 1 if len(ks) > 1 else 0
        parts.append(f"*={ks[max(0, q)]:.3f},{zs[max(0, q)]:.3f}")
    return ";".join(parts)


lines = [f"-- Accessories {batch}: build ReplicatedStorage.NHAccessories templates from the owner's imports. Generated by",
         "-- art/characters/accessories/acc_assemble.py; ids are group 15981569 images read by name. Re-runnable.",
         "local RS = game:GetService(\"ReplicatedStorage\")",
         "local SS = game:GetService(\"ServerStorage\")",
         "local store = RS:FindFirstChild(\"NHAccessories\") or Instance.new(\"Folder\")",
         "store.Name = \"NHAccessories\"",
         "store.Parent = RS",
         "local report = {}",
         "local function findImport(name)",
         "\tfor _, d in ipairs(workspace:GetDescendants()) do",
         "\t\tif d:IsA(\"Model\") and d.Name == name then return d end",
         "\tend",
         "\treturn nil",
         "end",
         "local ITEMS = {"]
def lua_str(s):
    return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""


for it in items:
    lay = json.load(open(os.path.join(ROOT, "layout", f"{it}.json")))
    xp = os.path.join(ROOT, "layout", f"{it}.extra.json")   # game-side behaviour (AccessoryFx): lights, orbit, idle...
    extra = json.load(open(xp)) if os.path.exists(xp) else {}
    lines.append(f"\t{it} = {{")
    for pn, e in lay["pieces"].items():
        fb = ";".join(f"{k}={v}" for k, v in sorted(e.get("fit_body", {}).items()) if abs(v - 1) > 1e-3)
        attrs = [f"Mount = \"{e['mount']}\"", f"Fit = {lua_v3(e['fit'])}", f"Size = {lua_v3(e['size'])}"]
        if fb:
            attrs.append(f"FitBody = \"{fb}\"")
        if e.get("sway"):
            attrs.append(f"Sway = \"{e['sway']}\"")
        if e.get("keepout"):
            attrs.append(f"KeepOut = {lua_v3(e['keepout'])}")
        if e.get("lock"):
            attrs.append(f"Lock = \"{e['lock']}\"")
        hf = hair_fit_string(e.get("hair_fit"))
        if hf:
            attrs.append(f"HairFit = \"{hf}\"")
        if e["kind"] == "Alpha":
            attrs.append(f"Alpha = \"{os.path.splitext(e['alpha_tex'])[0]}\"")
        x = extra.get(pn, {})
        if x.get("light"):
            L = x["light"]
            attrs.append("Light = { Color = Color3.fromRGB(%d, %d, %d); Range = %.2f; Brightness = %.2f; At = %s; Flicker = %s }" % (
                *[int(c) for c in L.get("color", (255, 200, 150))], float(L.get("range", 8)), float(L.get("brightness", 1)),
                lua_v3(L.get("at", e["fit"])), "true" if L.get("flicker") else "false"))
        if x.get("orbit"):
            attrs.append(f"Orbit = {lua_v3(x['orbit'].get('axis', (0, 1, 0)))}; Rpm = {float(x['orbit'].get('rpm', 6)):.3f}")
        if x.get("bob"):
            attrs.append(f"Bob = {float(x['bob']):.3f}")
        if x.get("idle"):
            attrs.append(f"Idle = {lua_str(x['idle'])}; Bones = {lua_str(json.dumps(x.get('bones', {}), separators=(',', ':')))}")
        if x.get("flare"):
            attrs.append("Flare = true")
        if x.get("trail"):
            attrs.append("Trail = true")
        lines.append(f"\t\t{pn} = {{ {'; '.join(attrs)} }};")
    glow = lay.get("glow")
    lines.append(f"\t\t_glow = {('Color3.new(%.3f, %.3f, %.3f)' % tuple(glow)) if glow else 'nil'};")
    lines.append("\t};")
lines.append("}")
lines.append("local IDS = {")
for k, v in sorted(IDS.items()):
    lines.append(f"\t[\"{k}\"] = {v};")
lines.append("}")
lines.append('''local function id(name)
	local v = IDS[name]
	return v and ("rbxassetid://" .. v) or nil
end
for item, pieces in pairs(ITEMS) do
	local m = findImport("NHAcc_" .. item)
	if not m then
		table.insert(report, item .. ": no import (NHAcc_" .. item .. ")")
		continue
	end
	for _, n in ipairs({ "AnimationController", "InitialPoses" }) do
		local c = m:FindFirstChild(n, true)
		if c then c:Destroy() end
	end
	local old = store:FindFirstChild(item)
	if old then
		local bk = SS:FindFirstChild("NH_Backup") or Instance.new("Folder", SS)
		bk.Name = "NH_Backup"
		local f = bk:FindFirstChild("Accessories_pre") or Instance.new("Folder", bk)
		f.Name = "Accessories_pre"
		old.Name = item .. "_" .. os.time()
		old.Parent = f
	end
	local tpl = Instance.new("Model")
	tpl.Name = item
	local got = 0
	for pn, a in pairs(pieces) do
		if pn == "_glow" then continue end
		local p = m:FindFirstChild(pn, true)
		if not (p and p:IsA("MeshPart")) then
			table.insert(report, item .. "." .. pn .. ": missing MeshPart")
			continue
		end
		p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Massless = true, false, false, false, true
		p.CastShadow = true
		p.TextureID = ""
		for _, s in ipairs(p:GetChildren()) do
			if s:IsA("SurfaceAppearance") then s:Destroy() end
		end
		local sa = Instance.new("SurfaceAppearance")
		if a.Alpha then
			sa.ColorMap = id(a.Alpha) or ""
			sa.AlphaMode = Enum.AlphaMode.Transparency
		else
			local base = "NHAcc_" .. item .. "_"
			sa.ColorMap = id(base .. "color") or ""
			sa.NormalMap = id(base .. "normal") or ""
			sa.RoughnessMap = id(base .. "roughness") or ""
			sa.MetalnessMap = id(base .. "metalness") or ""
			local em = id(base .. "emissive")
			if em then
				sa.EmissiveMaskContent = Content.fromUri(em)
				sa.EmissiveStrength = 2.2
				sa.EmissiveTint = pieces._glow or Color3.new(1, 1, 1)
			end
			sa.AlphaMode = Enum.AlphaMode.Overlay
		end
		sa.Parent = p
		p:SetAttribute("NHMount", a.Mount)
		p:SetAttribute("NHFit", CFrame.new(a.Fit))
		if a.FitBody then p:SetAttribute("NHFitBody", a.FitBody) end
		if a.Sway then p:SetAttribute("NHSway", a.Sway) end
		if a.KeepOut then p:SetAttribute("NHSwayKeepOut", a.KeepOut) end
		if a.Lock then p:SetAttribute("NHSwayLock", a.Lock) end
		if a.HairFit then p:SetAttribute("NHHairFit", a.HairFit) end
		if a.Mount == "Head" then p:SetAttribute("NHSeat", ''' + f"{SEAT:.3f}" + ''') end
		-- game-side behaviour (Controllers.Character.AccessoryFx)
		for _, c in ipairs(p:GetChildren()) do
			if c.Name == "NHLight" then c:Destroy() end
		end
		if a.Light then
			local at = Instance.new("Attachment")
			at.Name = "NHLight"
			at.Position = a.Light.At - a.Fit   -- mount space -> the piece's own (the fit has no turn)
			local l = Instance.new("PointLight")
			l.Color, l.Range, l.Brightness, l.Shadows = a.Light.Color, a.Light.Range, a.Light.Brightness, false
			if a.Light.Flicker then l:SetAttribute("NHFlicker", true) end
			l.Parent = at
			at.Parent = p
		end
		if a.Orbit then p:SetAttribute("NHOrbitAxis", a.Orbit) p:SetAttribute("NHOrbitRpm", a.Rpm) end
		if a.Bob then p:SetAttribute("NHBob", a.Bob) end
		if a.Idle then p:SetAttribute("NHIdle", a.Idle) p:SetAttribute("NHIdleBones", a.Bones) end
		if a.Flare then p:SetAttribute("NHFlare", true) end
		if a.Trail then p:SetAttribute("NHTrail", true) end
		-- the import re-centres each mesh on its bounding box: check it came in at the builder's size
		local d = (p.Size - a.Size).Magnitude
		if d > 0.02 then
			table.insert(report, string.format("%s.%s: size %s, builder %s (import scale?)", item, pn, tostring(p.Size), tostring(a.Size)))
		end
		local rx, ry, rz = p.CFrame:ToOrientation()
		if math.abs(rx) + math.abs(ry) + math.abs(rz) > 0.01 then
			table.insert(report, string.format("%s.%s: imported turned %.1f %.1f %.1f deg (check: the fit assumes upright)", item, pn, math.deg(rx), math.deg(ry), math.deg(rz)))
		end
		p.Parent = tpl
		got += 1
	end
	tpl.Parent = store
	m:Destroy()
	table.insert(report, string.format("%s: %d pieces", item, got))
end
return table.concat(report, "\\n")''')
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(OUT)

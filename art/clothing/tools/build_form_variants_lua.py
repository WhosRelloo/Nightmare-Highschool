"""Write ReplicatedStorage.UI.FormVariants (Luau) from the upload results.

    python Clothing/tools/build_form_variants_lua.py
Reads Clothing/seamfix/fv_ids/*.json (upload url -> asset id) and Clothing/variants/asset_ids.json
(piece -> the id the game wears it with). Writes Clothing/variants/forms/FormVariants.lua and
Clothing/variants/forms/form_variant_ids.json.
"""
import glob
import json
from pathlib import Path

import form_variants as fv

ROOT = Path(__file__).resolve().parents[1]
ids = {}
for f in sorted(glob.glob(str(ROOT / "seamfix" / "fv_ids" / "*.json"))):
    for url, aid in json.load(open(f)).items():
        form, name = url.split("/forms/")[1].split("/")
        ids.setdefault(name, {})[form.capitalize()] = aid.split("//")[1]
base = {k: v.split("//")[1] for k, v in json.load(open(ROOT / "variants" / "asset_ids.json")).items()}
for name, spec in list(fv.SHIRTS.items()) + list(fv.PANTS.items()):
    if spec:
        base[name] = spec[0]
missing = []
lines = []
for name in list(fv.SHIRTS) + list(fv.PANTS):
    got = ids.get(name, {})
    if set(got) != set(fv.FORMS):
        missing.append((name, sorted(set(fv.FORMS) - set(got))))
        continue
    parts = ", ".join(f'{f} = "rbxassetid://{got[f]}"' for f in fv.FORMS)
    lines.append(f'\t["{base[name]}"] = {{ {parts} }}, -- {name[:-4]}')
if missing:
    raise SystemExit(f"missing uploads: {missing}")
lua = (
    "--!strict\n"
    "--[[\n"
    "\tTransformation variants of every everyday clothing piece (generated by Clothing/tools/form_variants.py and\n"
    "\tbuild_form_variants_lua.py, 2026-11-04: do not hand-edit ids).\n"
    "\tKey: the template id the piece is worn with (Appearance.Uniforms / BottomsList / RaceUniforms).\n"
    "\tValue: that piece as it looks in each form. Appearance.FormVariant(form, template) reads this.\n"
    "]]\n"
    "return {\n" + "\n".join(lines) + "\n}\n"
)
out = ROOT / "variants" / "forms"
(out / "FormVariants.lua").write_text(lua, encoding="utf-8")
json.dump({base[n]: {"file": n, **{f: ids[n][f] for f in fv.FORMS}} for n in ids if n in base},
          open(out / "form_variant_ids.json", "w"), indent=1)
print(len(lines), "pieces written")

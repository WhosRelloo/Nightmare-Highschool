"""Writes tools/electives/live/ReplicatedStorage.Anatomy.Layout.luau from render/out/layout.json (export_bench.py).

The module gives the bench renderer every prop in bench space, in studs and Roblox axes:
  Blender (x right, y away from the student, z up) metres  ->  Roblox (x, z, -y) * SCALE studs
so the student (the camera) is toward +Z and the far side of the bench toward -Z.

Layout.Props.<Prop> = {
  Bones  = { <Bone> = { Head = Vector3, Parent = "<Bone>"|nil, Axis = Vector3|nil } },
  Pieces = { <Piece> = { Bone, Centre = Vector3, Size = Vector3, Color = Color3, Material = "<Enum name>",
                         Glow = bool, Glass = bool, Textures = { Color, Normal, Rough, Metal } (repo paths) } },
  Attach = { <Name> = { Bone, Pos = Vector3, Tool = "<Tool>"|nil } },
}
Piece names drop the "Anat<Prop>_" prefix (the imported MeshPart "AnatFrog_HeartPump" is the piece "HeartPump").

usage: python -X utf8 -I tools/electives/render/anatomy_layout.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SCALE = 10.0
sys_path = os.path.join(HERE, "export_bench.py")


def mat_table():
    # MAT_PROXY lives in export_bench.py (needs bpy to import): read the dict literal out of the source
    src = open(sys_path, encoding="utf-8").read()
    a = src.index("MAT_PROXY = {")
    b = src.index("}\n", a) + 1
    ns = {}
    exec(src[a:b], ns)
    return ns["MAT_PROXY"]


def v3(p):
    x, y, z = p
    return f"Vector3.new({x * SCALE:.4f}, {z * SCALE:.4f}, {-y * SCALE:.4f})"


def size3(s):
    x, y, z = s
    return f"Vector3.new({max(abs(x) * SCALE, 0.05):.4f}, {max(abs(z) * SCALE, 0.05):.4f}, {max(abs(y) * SCALE, 0.05):.4f})"


def axis3(a):
    x, y, z = a
    return f"Vector3.new({x}, {z}, {-y})"


def main():
    L = json.load(open(os.path.join(HERE, "out", "layout.json"), encoding="utf-8"))
    M = mat_table()
    out = ["-- ReplicatedStorage.Anatomy.Layout (generated by tools/electives/render/anatomy_layout.py from export_bench.py's",
           "-- layout.json; do not edit by hand). Every Anatomy prop in bench space: studs, Roblox axes, the student at +Z.",
           "local Layout = {}", f"Layout.Scale = {SCALE}", "Layout.Props = {}"]
    for prop in sorted(L):
        rec = L[prop]
        pre = rec["prop"] + "_"
        out.append(f"Layout.Props.{prop} = {{")
        out.append("\tBones = {")
        for bn, b in rec["bones"].items():
            parent = f'"{b["parent"]}"' if b.get("parent") else "nil"
            axis = axis3(b["axis"]) if b.get("axis") else "nil"
            out.append(f"\t\t{bn} = {{ Head = {v3(b['head'])}; Parent = {parent}; Axis = {axis} }};")
        out.append("\t};")
        out.append("\tPieces = {")
        for pn, bone in rec["pieces"].items():
            short = pn[len(pre):] if pn.startswith(pre) else pn
            mat = rec["mats"][pn]
            col, rmat = M.get(mat, ((0.7, 0.7, 0.7), "SmoothPlastic"))
            glow = short.endswith("Glow")
            glass = short.endswith("Glass")
            if glow:
                rmat = "Neon"
            if glass:
                rmat = "Glass"
            tex = {k: (v if v.startswith("art/") else "art/" + v) for k, v in (rec["textures"].get(pn) or {}).items()}
            texs = "nil" if not tex else "{ " + "; ".join(f'{k.capitalize()} = "{v}"' for k, v in sorted(tex.items())) + " }"
            out.append(f"\t\t{short} = {{ Bone = \"{bone}\"; Centre = {v3(rec['centres'][pn])}; Size = {size3(rec['sizes'][pn])}; "
                       f"Color = Color3.new({col[0]}, {col[1]}, {col[2]}); Material = \"{rmat}\"; Glow = {str(glow).lower()}; "
                       f"Glass = {str(glass).lower()}; Tris = {rec['tris'][pn]}; Textures = {texs} }};")
        out.append("\t};")
        out.append("\tAttach = {")
        for an, a in rec["attach"].items():
            tool = f'; Tool = "{a["tool"]}"' if a.get("tool") else ""
            out.append(f"\t\t{an} = {{ Bone = \"{a['bone']}\"; Pos = {v3(a['pos'])}{tool} }};")
        out.append("\t};")
        out.append("}")
    out.append("return Layout")
    dst = os.path.join(HERE, "..", "live", "ReplicatedStorage.Anatomy.Layout.luau")
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(dst), sorted(L))


if __name__ == "__main__":
    main()

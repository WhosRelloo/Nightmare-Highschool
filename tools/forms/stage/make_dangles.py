"""Writes, from <dest>/forms_dangles.json (form_bodies.py --dangles):
  tools/forms/live/ReplicatedStorage.Config.FormDangles.luau   the rest nodes FormDangles hangs per body and direction
  tools/forms/stage/dress_dangles.luau                         Studio Edit staging for the imported NHFormDangles model
usage: python -X utf8 -I make_dangles.py [path/to/forms_dangles.json]"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else "E:/NH-Work/forms/forms_dangles.json"
d = json.load(open(SRC, encoding="utf-8"))


def v3(v):
    return f"V({v[0]}, {v[1]}, {v[2]})"


def vlist(vs):
    return "{ " + ", ".join(v3(v) for v in vs) + " }"


rows = []
for body, b in d["bodies"].items():
    rows.append(f'\t{body} = {{')
    rows.append(f'\t\tLegOuter = {{ {b["legOuter"][0]}, {b["legOuter"][1]} }};')
    rows.append('\t\tR2 = {')
    for s in b["swags"]:
        rows.append(f'\t\t\t{{ Kind = "Swag"; Part = "{s["part"]}"; Pts = {vlist(s["pts"])}; Nrm = {vlist(s["nrm"])} }};')
    h = b["hang"]
    rows.append(f'\t\t\t{{ Kind = "Hang"; Part = "{h["part"]}"; Pts = {vlist(h["pts"])} }};')
    rows.append('\t\t};')
    rows.append('\t\tG2 = {')
    for t in b["tatters"]:
        rows.append(f'\t\t\t{{ Kind = "Tatter"; Part = "{t["part"]}"; W = {t["w"]}; Across = {v3(t["across"])}; Pts = {vlist(t["pts"])} }};')
    rows.append('\t\t};')
    rows.append('\t};')

cfg = '''--!strict
-- GENERATED by tools/forms/stage/make_dangles.py from forms_dangles.json (art/characters/transformations/form_bodies.py
-- --dangles): edit those, not this. The race-form pieces that hang (Functions.FormDangles), per body (UI.Appearance.Bodies
-- ids) and direction prefix: rest nodes in their R6 part's space at height 1 (Roblox axes: x right, y up, z back),
-- top first. Swag nodes carry their surface normals (they may only move out along them). LegOuter: how far each leg
-- (right, left) reaches out from the torso centre line.
local V = Vector3.new
return {
	Bodies = {
''' + "\n".join("\t" + r for r in rows) + '''
	};
}
'''
open(os.path.join(HERE, "..", "live", "ReplicatedStorage.Config.FormDangles.luau"), "w", encoding="utf-8").write(cfg)

wr = []
for body, b in d["bodies"].items():
    for nm, r in b["wraps"].items():
        c = r["centre"]
        wr.append(f'\t{{ "{body}", "{nm}", "{r["part"]}", Vector3.new({c[0]}, {c[1]}, {c[2]}) }};')

dress = '''--!nocheck
-- Race-form dangles staging (run in Studio Edit; never saves). GENERATED by tools/forms/stage/make_dangles.py.
-- Takes the imported NHFormDangles model (Workspace or ServerStorage.NHFormsImport; FBX imported with rig OFF):
--   Link, TatterSeg, TatterTip -> ReplicatedStorage.Assets.Forms.Dangles (Link wears R2Chains' SurfaceAppearance and
--     FormTint "Chain"; the strips wear G2WrapL's cloth), anchored, no collisions
--   G2WrapL_<body> / G2WrapR_<body> (the wraps without their baked tatters) replace Bodies.<body>.G2WrapL / G2WrapR,
--     keeping the old piece's SurfaceAppearance and attributes, with the new FormOffset
--   Bodies.<body>.R2Chains and R2Hang (the baked chains) are removed: FormDangles hangs them now.
local RS = game:GetService("ReplicatedStorage")
local WRAPS = {
''' + "\n".join(wr) + '''
}
local imp = game:GetService("ServerStorage"):FindFirstChild("NHFormsImport")
local src = workspace:FindFirstChild("NHFormDangles") or (imp and imp:FindFirstChild("NHFormDangles"))
if not src then return "NHFormDangles not found (Workspace or ServerStorage.NHFormsImport)" end
local forms = RS.Assets.Forms
local bodies = forms.Bodies
local std = bodies.standard
local chainSA = std:FindFirstChild("R2Chains") and std.R2Chains:FindFirstChildWhichIsA("SurfaceAppearance")
local clothSA = std:FindFirstChild("G2WrapL") and std.G2WrapL:FindFirstChildWhichIsA("SurfaceAppearance")
if not (chainSA and clothSA) then return "Bodies.standard R2Chains / G2WrapL SurfaceAppearance missing (run once only)" end
chainSA = chainSA:Clone(); clothSA = clothSA:Clone()
local function settle(p)
	p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false; p.Massless = true
end
local function find(name)
	for _, d in ipairs(src:GetDescendants()) do
		if d:IsA("MeshPart") and d.Name == name then return d end
	end
end
local out = {}
local dangles = forms:FindFirstChild("Dangles") or Instance.new("Folder")
dangles.Name = "Dangles"
dangles.Parent = forms
for _, n in ipairs({ "Link", "TatterSeg", "TatterTip" }) do
	local p = find(n)
	if not p then table.insert(out, "MISSING " .. n) continue end
	local old = dangles:FindFirstChild(n)
	if old then old:Destroy() end
	for _, c in ipairs(p:GetChildren()) do if c:IsA("SurfaceAppearance") then c:Destroy() end end
	local sa = (n == "Link" and chainSA or clothSA):Clone()
	sa.Parent = p
	p:SetAttribute("FormTint", n == "Link" and "Chain" or "None")
	p:SetAttribute("FormMaps", n == "Link" and "Horn" or "Cloth")
	settle(p)
	p.CastShadow = n == "Link"
	if n ~= "Link" then pcall(function() p.DoubleSided = true end) end
	p.Parent = dangles
	table.insert(out, n .. " " .. tostring(p.Size))
end
local swapped, removed = 0, 0
for _, w in ipairs(WRAPS) do
	local body, nm, part, off = w[1], w[2], w[3], w[4]
	local set = bodies:FindFirstChild(body)
	local p = find(nm .. "_" .. body)
	if not (set and p) then table.insert(out, "MISSING " .. nm .. "_" .. body) continue end
	local old = set:FindFirstChild(nm)
	for _, c in ipairs(p:GetChildren()) do if c:IsA("SurfaceAppearance") then c:Destroy() end end
	local sa = (old and old:FindFirstChildWhichIsA("SurfaceAppearance") or clothSA):Clone()
	sa.Parent = p
	if old then
		for k, v in pairs(old:GetAttributes()) do p:SetAttribute(k, v) end
		p.CastShadow = old.CastShadow
		old:Destroy()
	end
	p:SetAttribute("FormPart", part)
	p:SetAttribute("FormOffset", off)
	settle(p)
	pcall(function() p.DoubleSided = true end)
	p.Name = nm
	p.Parent = set
	swapped += 1
end
for _, set in ipairs(bodies:GetChildren()) do
	for _, n in ipairs({ "R2Chains", "R2Hang" }) do
		local p = set:FindFirstChild(n)
		if p then p:Destroy() removed += 1 end
	end
end
if #src:GetDescendants() == 0 or not src:FindFirstChildWhichIsA("BasePart", true) then src:Destroy() end
return table.concat(out, " | ") .. " | wraps swapped " .. swapped .. " | baked chains removed " .. removed
'''
open(os.path.join(HERE, "dress_dangles.luau"), "w", encoding="utf-8").write(dress)
print("wrote Config.FormDangles and dress_dangles.luau:", len(d["bodies"]), "bodies,", len(wr), "wraps")

"""Writes tools/forms/stage/dress_bodies.luau from art/characters/transformations/forms_body_fit.json (batch 2).
usage: python -X utf8 -I make_dress_bodies.py [fur_color_id fur_normal_id fur_rough_id]"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIT = os.path.join(HERE, "..", "..", "..", "art", "characters", "transformations", "forms_body_fit.json")
fit = json.load(open(FIT, encoding="utf-8"))
fur = sys.argv[1:4] if len(sys.argv) >= 4 else ["0", "0", "0"]

rows = []
for fname, pieces in fit.items():
    model = fname[:-4]
    rows.append(f'\t["{model}"] = {{')
    for name, r in pieces.items():
        c = r["centre"]
        rows.append(f'\t\t{name} = {{ "{r["part"]}", Vector3.new({c[0]}, {c[1]}, {c[2]}), "{r["maps"]}", "{r["tint"]}" }};')
    rows.append("\t};")

src = f'''--!nocheck
-- Race transformations, batch 2 staging (run in Studio Edit; never saves). GENERATED by make_dress_bodies.py from
-- art/characters/transformations/forms_body_fit.json: edit those, not this.
-- Dresses the 13 imported body-piece models (NHFormBody_<body>, NHFormHead; Workspace or ServerStorage.NHFormsImport):
-- SurfaceAppearances by map set, default tints, FormPart / FormOffset / FormTint / FormMaps on every MeshPart, no
-- collisions; then ReplicatedStorage.Assets.Forms.Bodies.<body> and Assets.Forms.NHFormHead.
-- FormOffset = the piece's centre from its R6 part's centre at height 1 (Roblox axes); the pieces face +Z like every
-- imported form, so FormParts places them at Part.CFrame * CFrame.new(FormOffset) * yaw180.
local RS = game:GetService("ReplicatedStorage")
local ID = {{
	Fur = {{ {fur[0]}, {fur[1]}, {fur[2]} }},
	Cloth = {{ 138112712699916, 70844911033119, 77793688753953 }},
	Mist = {{ 106250679469907, 129771447645641, 90005488644542 }},
	Ice = {{ 99796689341880, 104415262518492, 84690912729597 }},
	Bone = {{ 124233546569226, 94823965627909, 103382690601514 }},
	Horn = {{ 130451982169321, 83784713526082, 131027277593486 }},
}}
local SET = {{ fur = "Fur", cloth = "Cloth", mist = "Mist", ice = "Ice", bone = "Bone", horn = "Horn" }}
local SEE_THROUGH = {{ Mist = true, Ice = true }}
local DOUBLE = {{ fur = true, cloth = true, mist = true, ice = true }}
local rgb = Color3.fromRGB
local TINT = {{ Fur = rgb(110, 84, 62), Moss = rgb(74, 88, 52), Iron = rgb(58, 56, 60), Chain = rgb(150, 170, 192),
	WingFinish = rgb(214, 204, 180), HornFinish = rgb(30, 28, 34), WingPalette = rgb(52, 60, 112) }}
local NONE = {{ cloth = rgb(176, 170, 152), ice = rgb(236, 244, 255) }}
local FIT = {{
{chr(10).join(rows)}
}}

local function dress(p, maps, tint)
	local old = p:FindFirstChildWhichIsA("SurfaceAppearance")
	if old then old:Destroy() end
	local color = TINT[tint] or NONE[maps] or rgb(255, 255, 255)
	if maps == "glow" then
		p.Material = Enum.Material.Neon
		p.Color = rgb(222, 232, 255)
		return
	end
	local set = SET[maps]
	local ids = ID[set]
	if ids and ids[1] ~= 0 then
		local sa = Instance.new("SurfaceAppearance")
		sa.ColorMap = "rbxassetid://" .. ids[1]
		sa.NormalMap = "rbxassetid://" .. ids[2]
		sa.RoughnessMap = "rbxassetid://" .. ids[3]
		sa.AlphaMode = SEE_THROUGH[set] and Enum.AlphaMode.Transparency or Enum.AlphaMode.Overlay
		sa.Color = color
		sa.Name = "Form" .. set
		sa.Parent = p
	else
		p.Color = color
	end
	if DOUBLE[maps] then pcall(function() p.DoubleSided = true end) end
	p:SetAttribute("FormMaps", set or maps)
end

local function find(name)
	local imp = game:GetService("ServerStorage"):FindFirstChild("NHFormsImport")
	return workspace:FindFirstChild(name) or (imp and imp:FindFirstChild(name))
end

local assets = RS:WaitForChild("Assets")
local forms = assets:FindFirstChild("Forms")
local bodies = forms:FindFirstChild("Bodies") or Instance.new("Folder")
bodies.Name = "Bodies"
bodies.Parent = forms
local report, missing = {{}}, {{}}
for model, pieces in pairs(FIT) do
	local m = find(model)
	if not m then table.insert(missing, model) continue end
	local seen, n = {{}}, 0
	for _, p in ipairs(m:GetDescendants()) do
		local r = p:IsA("MeshPart") and pieces[p.Name]
		if not r then continue end
		dress(p, r[3], r[4])
		p:SetAttribute("FormPart", r[1])
		p:SetAttribute("FormOffset", r[2])
		p:SetAttribute("FormTint", r[4])
		p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false; p.Massless = true
		p.CastShadow = r[3] ~= "fur" -- hundreds of locks: no shadow cost
		seen[p.Name] = true
		n += 1
	end
	local lost = {{}}
	for name in pairs(pieces) do if not seen[name] then table.insert(lost, name) end end
	local body = model:match("^NHFormBody_(%a+)$")
	m.Name = body or model
	m.Parent = body and bodies or forms
	table.insert(report, m.Name .. " " .. n .. (#lost > 0 and (" MISSING " .. table.concat(lost, ",")) or ""))
end
table.sort(report)
return table.concat(report, " | ") .. (#missing > 0 and ("\\nnot found: " .. table.concat(missing, ", ")) or "")
'''
open(os.path.join(HERE, "dress_bodies.luau"), "w", encoding="utf-8").write(src)
print("wrote dress_bodies.luau", sum(len(p) for p in fit.values()), "pieces")

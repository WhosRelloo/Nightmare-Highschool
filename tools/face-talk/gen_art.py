import json, sys
m = json.load(open('art/manifest.json')); ids = json.load(open('art/ids.json'))
L = ['--[[', '\tUI.FaceTalkArt (2.0.0): the talking faces\' art, for Controllers.Character.FaceTalk. Generated by',
     '\ttools/face-talk/gen_art.py from tools/face-talk/build.py\'s manifest and the uploads.',
     '\tMouth: every expression x mouth shape x lips ("<expr>/<shape>/<m|f>"), each a band of rows Y0 .. Y0 + H of the',
     '\t1024 face (full width, so each face strip takes its own columns), packed into atlases. Keys = { atlas (0-based), row }.',
     '\tLid: each eye shape\'s squint lid at two levels ("<shape>/Soft" 0.25, "<shape>/Narrow" 0.42 closed), clipped to the eye.',
     '\tBrowY: the brows\' middle row (the brow slices turn about it). Expr: each expression\'s brow move and squint.', ']]',
     'return {']
for part in ('Mouth', 'Lid'):
    d = m[part]
    L.append(f'\t{part} = {{ Y0 = {d["Y0"]}; H = {d["H"]};')
    L.append('\t\tAtlases = { ' + ', '.join(f'"{ids[f]}"' for f in d['Atlases']) + ' };')
    L.append('\t\tKeys = {')
    for k, (a, r) in sorted(d['Keys'].items()):
        L.append(f'\t\t\t["{k}"] = {{ {a}, {r} }};')
    L.append('\t\t};')
    L.append('\t};')
L.append(f'\tBrowY = {m["BrowY"]};')
L.append('\tExpr = {')
for k, v in m['Expr'].items():
    L.append(f'\t\t{k} = {{ Brow = "{v["Brow"]}"; BrowAmt = {v["BrowAmt"]}; Squint = {v["Squint"]} }};')
L.append('\t};')
L.append('}')
open('out/ReplicatedStorage.UI.FaceTalkArt.luau', 'w', encoding='utf-8', newline='').write('\n'.join(L) + '\n')
print('ok', len(L))

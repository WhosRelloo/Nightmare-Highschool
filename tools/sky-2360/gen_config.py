FACES = ["Bk", "Dn", "Ft", "Lf", "Rt", "Up"]
ORDER = ["Ambient", "OutdoorAmbient", "Brightness", "ColorShiftTop", "ColorShiftBottom", "EnvDiffuse", "EnvSpecular",
         "ExposureCompensation", "Density", "Offset", "Haze", "Glare", "AtmosphereColor", "Decay",
         "CloudCover", "CloudDensity", "CloudColor", "GradeBrightness", "Contrast", "Saturation", "Tint",
         "Bloom", "BloomSize", "BloomThreshold", "SunRays", "SunRaysSpread"]
GROUPS = [("-- Lighting", ORDER[:8]), ("-- Atmosphere", ORDER[8:14]), ("-- Clouds", ORDER[14:17]),
          ("-- grade (NHDayGrade)", ORDER[17:21]), ("-- Bloom, SunRays", ORDER[21:])]


def val(v):
    if isinstance(v, tuple):
        return f"rgb({v[0]}, {v[1]}, {v[2]})"
    if isinstance(v, float):
        s = f"{v:.3f}".rstrip("0").rstrip(".")
        return s if s not in ("-0", "") else "0"
    return str(v)


def fields(d, indent):
    parts = [f"{k} = {val(d[k])};" for k in ORDER if k in d]
    return indent + " ".join(parts)


def look_block(name, d):
    lines = [f"local {name} = {{"]
    for title, keys in GROUPS:
        parts = [f"{k} = {val(d[k])};" for k in keys]
        lines.append(f"\t{' '.join(parts)}  {title}")
    lines.append("}")
    return "\n".join(lines)


def keys_block(keys, indent="\t\t"):
    return "\n".join(f"{indent}{{ {h}, {k} }};" for h, k in keys)


def sched_block(sched, indent="\t\t\t"):
    return "\n".join(f"{indent}{{ {h}, `{s}` }};" for h, s in sched)


def ids(d):
    return "{ " + "; ".join(f"{f} = {d[f]}" for f in FACES) + " }"


def empty():
    return "{ " + "; ".join(f"{f} = 0" for f in FACES) + " }"


def mod_block(m, indent):
    out = []
    for part in ("Mul", "Add", "Set"):
        if m.get(part):
            body = " ".join(f"{k} = {val(v)};" for k, v in m[part].items())
            out.append(f"{indent}{part} = {{ {body} }};")
    if m.get("Sky"):
        out.append(f"{indent}Sky = `{m['Sky']}`;")
    if m.get("StarCount"):
        out.append(f"{indent}StarCount = {m['StarCount']};  -- applied by World.MoonPhases (it owns the stars)")
    return "\n".join(out)



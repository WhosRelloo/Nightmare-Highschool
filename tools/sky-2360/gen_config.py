    L.append(f"\tNightWeight = {{ Rise = {{ {P.NIGHT_WEIGHT['Rise'][0]}, {P.NIGHT_WEIGHT['Rise'][1]} }}; "
             f"Fall = {{ {P.NIGHT_WEIGHT['Fall'][0]}, {P.NIGHT_WEIGHT['Fall'][1]} }} }};")

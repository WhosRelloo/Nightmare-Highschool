"""Build ReplicatedStorage.UI.EyeArt (Luau) from the uploaded asset ids.
usage: python build_eyeart.py [ids.json]  ->  tex/EyeArt.lua"""
import json, sys

ids = json.load(open(sys.argv[1] if len(sys.argv) > 1 else "tex/eye_ids.json"))
SHAPES = [("sharp", "Sharp"), ("hooded", "Hooded"), ("fierce", "Fierce"), ("doe", "Doe"),
          ("sleepless", "Sleepless"), ("cat", "Cat"), ("gentle", "Gentle"), ("calm", "Calm")]
FORMS = ["base", "vampire", "wolf", "ghoul", "wraith", "vampire2", "ghoul2"]
BROWS = [("straight", "Straight"), ("arched", "Arched"), ("angled", "Angled"), ("soft", "Soft"), ("thick", "Thick"),
         ("thin", "Thin"), ("furrowed", "Furrowed"), ("raised", "Raised"), ("bold", "Bold"), ("heavy", "Heavy"), ("bushy", "Bushy"),
         ("sleek", "Sleek"), ("flatthick", "Flat Thick"), ("higharch", "High Arch"), ("sharparch", "Sharp Arch"), ("worried", "Worried"),
         ("angry", "Angry"), ("feathered", "Feathered"), ("wisp", "Wisp"), ("tapered", "Tapered"), ("rounded", "Rounded")]
MOUTHS = [("neutral", "Neutral"), ("smile", "Smile"), ("flat", "Flat"), ("smirk", "Smirk"), ("hint", "Hint"), ("grin", "Grin"),
          ("small", "Small"), ("ooh", "Ooh"), ("open", "Open"), ("talk", "Talk"), ("laugh", "Laugh"), ("shout", "Shout"),
          ("pout", "Pout"), ("frown", "Frown"), ("scowl", "Scowl"), ("sulk", "Sulk"), ("grimace", "Grimace"),
          ("cat", "Cat"), ("fang", "Fang"), ("shark", "Shark")]
MFORMS = ["vampire", "wolf", "ghoul", "wraith"]

L = ["--!nonstrict", "--[[",
     "\tNH painted face art. Generated by Tools/ui-textures (gen_eyes.py, gen_face.py, build_eyeart.py): do not hand-edit ids.",
     "\tEyes: two Decals for a classic head front face (plus a vein layer for vampire / ghoul forms):",
     "\t  Iris  greyscale iris, tinted in game with Decal.Color3 (ZIndex 1)",
     "\t  Main  sclera, lids, lashes, pupil, highlights (ZIndex 2)",
     "\t  Veins greyscale skin veins, tinted from the character's skin colour (ZIndex 1)",
     "\tKey \"<shape>_<m|f>_<form>\", form = base | vampire | wolf | ghoul | wraith | vampire2 | ghoul2 (2 = jet-black sclera).",
     "\tBrows (tinted, fitted per eye shape so they never touch the lashes) and mouths are separate decals.",
     "]]", "", "local EyeArt = {}", "", "EyeArt.Shapes = {"]
L += [f'\t{{ Id = "{a}", Name = "{b}" }},' for a, b in SHAPES] + ["}"]
L.append("EyeArt.Forms = { " + ", ".join(f'"{f}"' for f in FORMS) + " }")
L.append("EyeArt.BrowStyles = {")
L += [f'\t{{ Id = "{a}", Name = "{b}" }},' for a, b in BROWS] + ["}"]
L.append("EyeArt.MouthStyles = {")
L += [f'\t{{ Id = "{a}", Name = "{b}" }},' for a, b in MOUTHS] + ["}", ""]

missing = []
L.append("EyeArt.Art = {")
for sid, _ in SHAPES:
    for sx in "mf":
        for form in FORMS:
            k = f"{sid}_{sx}_{form}"
            a, b, v = ids.get(f"eyes_{k}_iris.png"), ids.get(f"eyes_{k}_main.png"), ids.get(f"eyes_{k}_veins.png")
            if a and b:
                extra = f', Veins = "{v}"' if v else ""
                L.append(f'\t{k} = {{ Iris = "{a}", Main = "{b}"{extra} }},')
            else:
                missing.append(k)
L += ["}", "", "EyeArt.BrowArt = {"]
for st, _ in BROWS:
    for sid, _ in SHAPES:
        v = ids.get(f"brow_{st}_{sid}.png")
        if v:
            L.append(f'\t{st}_{sid} = "{v}",')
        else:
            missing.append(f"brow_{st}_{sid}")
L += ["}", "", "EyeArt.MouthArt = {"]
for st, _ in MOUTHS:
    for sx in "mf":
        v = ids.get(f"mouth_{st}_{sx}.png")
        if v:
            L.append(f'\t{st}_{sx} = "{v}",')
        else:
            missing.append(f"mouth_{st}_{sx}")
for fm in MFORMS:
    v = ids.get(f"mouth_{fm}.png")
    if v:
        L.append(f'\t{fm} = "{v}",')
    else:
        missing.append(f"mouth_{fm}")
L.append("}")
L.append('''
function EyeArt.Get(shape: string, set: string?, form: string?)
	set = set or "m"
	form = form or "base"
	local A = EyeArt.Art
	local baseForm = string.gsub(form, "2$", "")
	return A[`{shape}_{set}_{form}`] or A[`{shape}_m_{form}`] or A[`{shape}_{set}_{baseForm}`] or A[`{shape}_m_{baseForm}`]
		or A[`{shape}_{set}_base`] or A[`{shape}_m_base`]
end

function EyeArt.Brow(style: string, shape: string?)
	return EyeArt.BrowArt[`{style}_{shape or "sharp"}`] or EyeArt.BrowArt[`{style}_sharp`]
end

function EyeArt.Mouth(style: string, fullLips: boolean?)
	return EyeArt.MouthArt[`{style}_{fullLips and "f" or "m"}`] or EyeArt.MouthArt[`{style}_m`]
end

function EyeArt.FormMouth(form: string)
	return EyeArt.MouthArt[(string.gsub(form, "2$", ""))]
end

return EyeArt''')
open("tex/EyeArt.lua", "w", encoding="utf-8").write("\n".join(L) + "\n")
print("missing", len(missing), missing[:8])
